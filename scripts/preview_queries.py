"""Writes a readable Markdown preview of the generated query files for review."""

import json
import sys
from collections import Counter
from pathlib import Path

from bench.generate import (
    Query,
    generate_collisions,
    generate_dev,
    generate_stepped,
    queries_from_json,
)
from bench.inventory import App

RULES = ["full", "nospace", "initials", "prefix1", "prefix2", "prefix3", "prefix4", "typo"]


def _counts(dev: list[Query], collisions: list[Query], stepped: list[Query]) -> dict[str, int]:
    ambiguous = sum(q.ambiguous for q in dev)
    return {
        "dev": len(dev),
        "dev ambiguous": ambiguous,
        "dev unambiguous": len(dev) - ambiguous,
        "collisions": len(collisions),
        "stepped": len(stepped),
    }


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    return lines + ["| " + " | ".join(r) + " |" for r in rows]


def main(inventory_path: str, data_dir: str, out_path: str) -> int:
    data = json.loads(Path(inventory_path).read_text())
    inventory = [App(**a) for a in data["apps"]]
    kind_of = {a.name: a.kind for a in inventory}
    dev, collisions, stepped = (
        queries_from_json((Path(data_dir) / f"{name}-queries.json").read_text())
        for name in ("dev", "collision", "stepped")
    )
    now = _counts(dev, collisions, stepped)
    builtins = [a for a in inventory if a.kind == "builtin"]
    before = _counts(
        generate_dev(builtins), generate_collisions(builtins), generate_stepped(builtins)
    )
    apps_by_kind = Counter(a.kind for a in inventory)

    lines = [
        f"# Query preview ({len(inventory)} apps, macOS {data['macos']['version']} "
        f"build {data['macos']['build']}, snapshot `{data['base_snapshot']}`)",
        "",
        "Generated by `python -m bench queries` (files in `data/`) and "
        "`scripts/preview_queries.py`.",
        "",
        "Apps by kind: " + ", ".join(f"{k} {v}" for k, v in sorted(apps_by_kind.items())) + ".",
        "Tools under test are never intended targets but count in acceptable sets (spec §13.3).",
        "",
        "## Totals, and change from the built-ins-only preview",
        "",
    ]
    lines += _table(
        ["", "Built-ins only", "Now", "Change"],
        [[k, str(before[k]), str(now[k]), f"{now[k] - before[k]:+d}"] for k in now],
    )

    lines += ["", "## Dev queries by rule and app kind", ""]
    kinds = sorted({kind_of[q.intended.id] for q in dev if q.intended})
    rows = []
    for rule in RULES:
        qs = [q for q in dev if q.rule == rule]
        amb = sum(q.ambiguous for q in qs)
        per_kind = [
            str(sum(1 for q in qs if q.intended and kind_of[q.intended.id] == k)) for k in kinds
        ]
        rows.append([rule, str(len(qs)), *per_kind, str(amb), str(len(qs) - amb)])
    total_amb = sum(q.ambiguous for q in dev)
    per_kind_total = [
        str(sum(1 for q in dev if q.intended and kind_of[q.intended.id] == k)) for k in kinds
    ]
    rows.append(
        ["**all**", str(len(dev)), *per_kind_total, str(total_amb), str(len(dev) - total_amb)]
    )
    lines += _table(["Rule", "Total", *kinds, "Ambiguous", "Unambiguous"], rows)

    lines += ["", "## Suites", ""]
    suite_rows = []
    for name, qs in [("dev", dev), ("collisions", collisions), ("stepped", stepped)]:
        modes = ", ".join(f"{m} {n}" for m, n in sorted(Counter(q.mode for q in qs).items()))
        suite_rows.append([name, str(len(qs)), str(sum(q.ambiguous for q in qs)), modes])
    lines += _table(["Suite", "Queries", "Ambiguous", "Mode"], suite_rows)

    lines += [
        "",
        "## Every dev query, by app and rule",
        "",
        "`*` = ambiguous: more than one app is acceptable (listed after the arrow).",
        "",
    ]
    by_app: dict[str, list[Query]] = {}
    for q in dev:
        assert q.intended is not None
        by_app.setdefault(q.intended.id, []).append(q)
    for app in sorted(by_app, key=str.lower):
        lines.append(f"### {app} ({kind_of[app]})")
        lines.append("")
        for q in sorted(by_app[app], key=lambda q: RULES.index(q.rule)):
            others = sorted(t.id for t in q.acceptable if t.id != app)
            suffix = "* → also " + ", ".join(others) if q.ambiguous else ""
            lines.append(f"- {q.rule}: `{q.text}`{suffix}")
        lines.append("")

    lines += ["## Collision prefixes (no single right answer)", ""]
    lines += _table(
        ["Typed", "Acceptable"],
        [[f"`{q.text}`", ", ".join(sorted(t.id for t in q.acceptable))] for q in collisions],
    )
    lines += ["", "## Stepped (each app typed one key at a time)", ""]
    lines.append(", ".join(f"`{q.text}`" for q in stepped))
    Path(out_path).write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2], sys.argv[3]))
